import asyncio, json
from playwright.async_api import async_playwright
URL = __import__("sys").argv[1]
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        ctx = await b.new_context(viewport={"width": 390, "height": 844}, device_scale_factor=2)
        pg = await ctx.new_page()
        errs = []; pg.on("pageerror", lambda e: errs.append(str(e))); pg.on("console", lambda m: m.type == "error" and errs.append(m.text))
        await pg.goto(URL); await pg.wait_for_timeout(1200)
        st = lambda: pg.evaluate("JSON.parse(localStorage.getItem('mi_save_v1'))")
        s = await st(); print("after load: coins", s["coins"], "daily", s["daily"])
        await pg.get_by_text("🏆 竞赛挑战").click(); await pg.wait_for_timeout(400)
        await pg.screenshot(path="/tmp/r1.png")
        await pg.locator("text=找规律填数：2，4，6，8").first.click(); await pg.wait_for_timeout(300)
        await pg.get_by_role("button", name="1", exact=True).click(); await pg.get_by_role("button", name="0", exact=True).click()
        await pg.get_by_role("button", name="确定", exact=True).click(); await pg.wait_for_timeout(600)
        await pg.screenshot(path="/tmp/r2.png", full_page=True)
        s = await st(); print("after comp: coins", s["coins"], "xp", s["xp"], "comp", s["comp"], "ach", s["ach"])
        # wrong answer path on a choice problem -> hints
        await pg.get_by_text("← 题目列表").click(); await pg.locator("text=第 20 个图形").first.click()
        await pg.get_by_role("button", name="○", exact=True).click(); await pg.wait_for_timeout(300)
        print("hint shown:", await pg.locator("text=提示1").count())
        await pg.get_by_role("button", name="△", exact=True).click(); await pg.wait_for_timeout(300)
        s = await st(); print("after hinted correct: coins", s["coins"])
        await pg.get_by_text("🛍️ 商店").click(); await pg.wait_for_timeout(400)
        await pg.locator("button:has-text('阳光教室')").click(); await pg.wait_for_timeout(500)
        await pg.screenshot(path="/tmp/r3.png")
        s = await st(); print("after buy: coins", s["coins"], "owned", s["owned"], "equip", s["equip"])
        await pg.reload(); await pg.wait_for_timeout(1200)
        s = await st(); print("after reload: coins", s["coins"], "equip", s["equip"], "comp solved", len(s["comp"]))
        await pg.get_by_text("👕 我的形象").click(); await pg.wait_for_timeout(1500)
        await pg.screenshot(path="/tmp/r4.png", full_page=True)
        # give coins to test chest + epic preview
        await pg.evaluate("(()=>{const s=JSON.parse(localStorage.getItem('mi_save_v1'));s.chests=2;localStorage.setItem('mi_save_v1',JSON.stringify(s))})()")
        await pg.reload(); await pg.wait_for_timeout(800)
        await pg.get_by_text("🎁 成就宝箱").click(); await pg.get_by_text("打开宝箱").click(); await pg.wait_for_timeout(600)
        await pg.screenshot(path="/tmp/r5.png")
        s = await st(); print("after chest: coins", s["coins"], "chests", s["chests"], "owned", s["owned"])
        await pg.get_by_text("闯关地图").click(); await pg.wait_for_timeout(500)
        await pg.screenshot(path="/tmp/r6.png")
        print("errors:", errs)
        await b.close()
asyncio.run(main())
